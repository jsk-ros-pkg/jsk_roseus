// rclcpp::QoS for subscribing topic, which is compatible with the publishers
rclcpp::QoS subscription_qos(const string & topic, int queuesize) {
  rclcpp::QoS qos(rclcpp::KeepLast(queuesize > 0 ? queuesize : 1));
  std::vector<rclcpp::TopicEndpointInfo> infos;
  try {
    infos = s_node->get_publishers_info_by_topic(topic);
  } catch (const std::exception &) {
  }
  if (!infos.empty()) {
    bool all_transient_local = true;
    bool any_best_effort = false;
    for (auto & info : infos) {
      if (info.qos_profile().durability() != rclcpp::DurabilityPolicy::TransientLocal)
        all_transient_local = false;
      if (info.qos_profile().reliability() == rclcpp::ReliabilityPolicy::BestEffort)
        any_best_effort = true;
    }
    if (all_transient_local) qos.transient_local();
    if (any_best_effort) qos.best_effort();
  }
  return qos;
}

pointer ROSEUS_SUBSCRIBE(register context *ctx,int n,pointer *argv)
{
  isInstalledCheck;
  string topicname;
  pointer message, fncallback, args;
  int queuesize = 1;

  // ;; arguments ;;
  // topicname message_type callbackfunc args0 ... argsN [ queuesize ] [ :groupname groupname ]
  if (!isstring(argv[0])) error(E_NOSTRING);
  string groupname;
  Group *group = nullptr;
  if (parse_groupname(n, argv, groupname)) {
    group = find_group(groupname);
    if (!group) {
      ROSEUS_ERROR("Groupname %s is missing. Topic %s is not subscribed. Call (ros::create-nodehandle \"%s\") first.",
                   groupname.c_str(), eus_string(argv[0]).c_str(), groupname.c_str());
      return (NIL);
    }
  }
  topicname = resolve_name(eus_string(argv[0]), false, group ? group->ns : "");
  if (isint(argv[n-1])) {queuesize = ckintval(argv[n-1]);n--;}
  ROSEUS_DEBUG("subscribe %s queuesize=%d", topicname.c_str(), queuesize);
  message = argv[1];
  fncallback = argv[2];
  args=NIL;
  for (int i=n-1;i>=3;i--) args=cons(ctx,argv[i],args);
  vpush(args);

  pointer cls = message_class(message);
  string datatype = message_datatype(ctx, cls);
  protect_from_gc(ctx, fncallback, args);
  auto cb = std::make_shared<EusCallback>();
  cb->fn = callback_function(fncallback);
  cb->args = args;
  cb->msg_class = cls;
  vpop(); // args

  rclcpp::SubscriptionOptions options;
  if (group) options.callback_group = group->callback_group;
  rclcpp::GenericSubscription::SharedPtr sub;
  try {
    sub = s_node->create_generic_subscription(
      topicname, datatype, subscription_qos(topicname, queuesize),
      [cb](std::shared_ptr<const rclcpp::SerializedMessage> msg) {
        context *ctx = current_ctx;
        pointer obj = serialized_to_eus(ctx, cb->msg_class, *msg);
        vpush(obj);
        call_eus_function(ctx, cb->fn, cb->args, obj);
        vpop();
      }, options);
  } catch (const std::exception & e) {
    ROSEUS_ERROR("failed to subscribe %s [%s]: %s", topicname.c_str(), datatype.c_str(), e.what());
    return (NIL);
  }
  s_staticdata.mapSubscribed[topicname] = sub;
  return (T);
}

