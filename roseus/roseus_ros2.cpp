pointer param_to_eus(context *ctx, const rclcpp::Parameter & param) {
  numunion nu;
  pointer ret = NIL;
  int count = 0;
  switch (param.get_type()) {
  case rclcpp::ParameterType::PARAMETER_BOOL:
    return param.as_bool() ? T : NIL;
  case rclcpp::ParameterType::PARAMETER_INTEGER:
    return makeint(param.as_int());
  case rclcpp::ParameterType::PARAMETER_DOUBLE:
    return makeflt(param.as_double());
  case rclcpp::ParameterType::PARAMETER_STRING:
    return make_eus_string(param.as_string());
  case rclcpp::ParameterType::PARAMETER_BYTE_ARRAY: {
    auto v = param.as_byte_array();
    for (auto it = v.rbegin(); it != v.rend(); ++it) { ret = cons(ctx, makeint(*it), ret); vpush(ret); count++; }
    break; }
  case rclcpp::ParameterType::PARAMETER_BOOL_ARRAY: {
    auto v = param.as_bool_array();
    for (auto it = v.rbegin(); it != v.rend(); ++it) { ret = cons(ctx, *it ? T : NIL, ret); vpush(ret); count++; }
    break; }
  case rclcpp::ParameterType::PARAMETER_INTEGER_ARRAY: {
    auto v = param.as_integer_array();
    for (auto it = v.rbegin(); it != v.rend(); ++it) { ret = cons(ctx, makeint(*it), ret); vpush(ret); count++; }
    break; }
  case rclcpp::ParameterType::PARAMETER_DOUBLE_ARRAY: {
    auto v = param.as_double_array();
    for (auto it = v.rbegin(); it != v.rend(); ++it) { ret = cons(ctx, makeflt(*it), ret); vpush(ret); count++; }
    break; }
  case rclcpp::ParameterType::PARAMETER_STRING_ARRAY: {
    auto v = param.as_string_array();
    for (auto it = v.rbegin(); it != v.rend(); ++it) {
      pointer s = make_eus_string(*it); vpush(s);
      ret = cons(ctx, s, ret); vpop(); vpush(ret); count++; }
    break; }
  default:
    return NIL;
  }
  while (count-- > 0) vpop();
  return ret;
}

// parameters under name. as an alist (("key" . value) ...), or :none
pointer params_to_alist(context *ctx, const string & name) {
  auto result = s_node->list_parameters({name}, 0);
  std::set<string> children;
  for (auto & full : result.names) {
    if (full.compare(0, name.size() + 1, name + ".") != 0) continue;
    string rest = full.substr(name.size() + 1);
    children.insert(rest.substr(0, rest.find('.')));
  }
  if (children.empty()) return NIL;
  pointer ret = NIL;
  int count = 0;
  for (auto it = children.rbegin(); it != children.rend(); ++it) {
    string child = name + "." + *it;
    pointer v;
    rclcpp::Parameter param;
    if (s_node->get_parameter(child, param) &&
        param.get_type() != rclcpp::ParameterType::PARAMETER_NOT_SET) {
      v = param_to_eus(ctx, param);
    } else {
      v = params_to_alist(ctx, child);
    }
    vpush(v);
    pointer key = make_eus_string(*it);
    vpush(key);
    pointer kv = cons(ctx, key, v);
    vpop(); vpop();
    vpush(kv);
    ret = cons(ctx, kv, ret);
    vpop();
    vpush(ret); count++;
  }
  while (count-- > 0) vpop();
  return ret;
}

pointer get_param(context *ctx, const string & name, bool & found) {
  rclcpp::Parameter param;
  found = false;
  if (s_node->get_parameter(name, param) &&
      param.get_type() != rclcpp::ParameterType::PARAMETER_NOT_SET) {
    found = true;
    return param_to_eus(ctx, param);
  }
  pointer r = params_to_alist(ctx, name);
  if (r != NIL) found = true;
  return r;
}

