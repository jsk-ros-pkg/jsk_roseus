// "pkg/srv/Foo_Request" -> "pkg/srv/Foo"
string service_type_of_request(context *ctx, pointer request) {
  string datatype = message_datatype(ctx, request);
  const string suffix = "_Request";
  if (datatype.size() <= suffix.size() ||
      datatype.compare(datatype.size() - suffix.size(), suffix.size(), suffix) != 0) {
    ROSEUS_ERROR("%s is not a service request", datatype.c_str());
    error(E_USER, "not a service request");
  }
  return datatype.substr(0, datatype.size() - suffix.size());
}

