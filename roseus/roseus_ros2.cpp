void package_depends(const string & pkg, std::vector<string> & deps, std::set<string> & visited) {
  string path;
  try {
    path = ament_index_cpp::get_package_share_directory(pkg);
  } catch (const std::exception &) {
    return;
  }
  std::ifstream f(path + "/package.xml");
  if (!f) return;
  std::stringstream ss;
  ss << f.rdbuf();
  string xml = ss.str();
  static const std::regex re(
    "<(depend|build_depend|exec_depend|run_depend|build_export_depend|buildtool_depend|buildtool_export_depend)"
    "(\\s[^>]*)?>\\s*([A-Za-z0-9_]+)\\s*</");
  std::vector<string> direct;
  for (auto it = std::sregex_iterator(xml.begin(), xml.end(), re); it != std::sregex_iterator(); ++it) {
    string attr = (*it)[2].str();
    // skip the dependencies for ROS 1
    if (attr.find("ROS_VERSION == 1") != string::npos) continue;
    direct.push_back((*it)[3].str());
  }
  for (auto & d : direct) {
    if (visited.count(d)) continue;
    visited.insert(d);
    try {
      ament_index_cpp::get_package_share_directory(d);
    } catch (const std::exception &) {
      continue;
    }
    package_depends(d, deps, visited);
    deps.push_back(d);
  }
}

