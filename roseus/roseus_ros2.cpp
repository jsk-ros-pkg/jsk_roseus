string eus_string(pointer p) {
  if (isstring(p)) return string((char *)p->c.str.chars, intval(p->c.str.length));
  if (issymbol(p)) return string((char *)p->c.sym.pname->c.str.chars);
  error(E_NOSTRING);
  return string();
}

pointer make_eus_string(const string & s) {
  return makestring((char *)s.c_str(), s.length());
}

// protect a callback function and its arguments from GC
void protect_from_gc(context *ctx, pointer fn, pointer args) {
  pointer p = gensym(ctx);
  setval(ctx, intern(ctx, (char*)(p->c.sym.pname->c.str.chars),
                     strlen((char*)(p->c.sym.pname->c.str.chars)), lisppkg),
         cons(ctx, fn, args));
}

pointer callback_function(pointer scb) {
  if (piscode(scb)) { // compiled code
    return scb;
  } else if ((ccar(scb)) == LAMCLOSURE) { // uncompiled code
    if (ccar(ccdr(scb)) != NIL) { // function
      return ccar(ccdr(scb));
    } else { // lambda function
      return scb;
    }
  }
  ROSEUS_ERROR("callback function install error");
  return scb;
}

// call fn with args ... and the last argument
pointer call_eus_function(context *ctx, pointer fn, pointer args, pointer last) {
  pointer argp = args;
  int argc = 0;
  if ( ! ( issymbol(fn) || piscode(fn) || ccar(fn)==LAMCLOSURE ) ) {
    ROSEUS_ERROR("%s : can't find callback function", __PRETTY_FUNCTION__);
  }
  while (argp != NIL) { ckpush(ccar(argp)); argp = ccdr(argp); argc++; }
  vpush(last); argc++;
  pointer r = ufuncall(ctx, (ctx->callfp?ctx->callfp->form:NIL), fn, (pointer)(ctx->vsp-argc), NULL, argc);
  while (argc-- > 0) vpop();
  return r;
}

pointer message_class(pointer message) {
  if (isclass(message)) return message;
  return classof(message);
}

// make an instance of cls, and call :init
pointer instantiate_message(context *ctx, pointer cls) {
  pointer obj = makeobject(cls);
  vpush(obj);
  csend(ctx, obj, K_ROSEUS_INIT, 0);
  vpop();
  return obj;
}

bool has_method(context *ctx, pointer obj, pointer method) {
  pointer curclass;
  return ispointer(obj) && (pointer)findmethod(ctx, method, classof(obj), &curclass) != NIL;
}

// (get cls :datatype-), e.g. "std_msgs/msg/String"
string message_datatype(context *ctx, pointer message) {
  pointer cls = message_class(message);
  pointer r = csend(ctx, cls, K_ROSEUS_GET, 1, K_ROSEUS_DATATYPE);
  if (!isstring(r)) {
    ROSEUS_ERROR("could not find the :datatype- of the message class");
    error(E_USER, "not a roseus message class");
  }
  return eus_string(r);
}

// EusLisp message -> serialized message (with the encapsulation header)
void eus_to_serialized(context *ctx, pointer message, rclcpp::SerializedMessage & serialized) {
  if (!has_method(ctx, message, K_ROSEUS_SERIALIZE)) {
    error(E_USER, "message does not have :serialize method");
  }
  pointer r = csend(ctx, message, K_ROSEUS_SERIALIZE, 0);
  if (!isstring(r)) error(E_USER, ":serialize does not return string");
  size_t len = intval(r->c.str.length);
  serialized.reserve(len + 4);
  rcl_serialized_message_t & m = serialized.get_rcl_serialized_message();
  memcpy(m.buffer, CDR_LE_HEADER, 4);
  memcpy(m.buffer + 4, r->c.str.chars, len);
  m.buffer_length = len + 4;
}

// serialized message -> EusLisp message
pointer serialized_to_eus(context *ctx, pointer cls, const rclcpp::SerializedMessage & serialized) {
  const rcl_serialized_message_t & m = serialized.get_rcl_serialized_message();
  pointer obj = instantiate_message(ctx, cls);
  vpush(obj);
  if (m.buffer_length < 4) {
    ROSEUS_ERROR("invalid serialized message (%ld bytes)", (long)m.buffer_length);
  } else {
    if (m.buffer[1] != 0x01) {
      ROSEUS_ERROR("only little endian CDR is supported (encapsulation %02x %02x)",
                   m.buffer[0], m.buffer[1]);
    }
    pointer s = makestring((char *)(m.buffer + 4), m.buffer_length - 4);
    vpush(s);
    csend(ctx, obj, K_ROSEUS_DESERIALIZE, 1, s);
    vpop();
  }
  vpop();
  return obj;
}

// ROS 1 style "~foo" -> ROS 2 "~/foo"
string ros2_name(const string & name) {
  if (name.size() > 1 && name[0] == '~' && name[1] != '/') {
    return "~/" + name.substr(1);
  }
  return name;
}

string resolve_name(const string & name, bool is_service = false, const string & ns = "") {
  string n = ros2_name(name);
  if (!ns.empty() && !n.empty() && n[0] != '/' && n[0] != '~') {
    n = ns + "/" + n;
  }
  if (!s_node) return n;
  rcl_allocator_t allocator = rcl_get_default_allocator();
  char * output = nullptr;
  rcl_ret_t ret = rcl_node_resolve_name(
    s_node->get_node_base_interface()->get_rcl_node_handle(),
    n.c_str(), allocator, is_service, false, &output);
  if (ret != RCL_RET_OK) {
    ROSEUS_ERROR("failed to resolve name %s: %s", n.c_str(), rcl_get_error_string().str);
    rcl_reset_error();
    return n;
  }
  string resolved(output);
  allocator.deallocate(output, allocator.state);
  return resolved;
}

// parse [:groupname "name"] at the end of the arguments, return the group or nullptr
bool parse_groupname(int & n, pointer *argv, string & groupname) {
  if (n > 1 && issymbol(argv[n-2]) && isstring(argv[n-1]) && argv[n-2] == K_ROSEUS_GROUPNAME) {
    groupname = eus_string(argv[n-1]);
    n -= 2;
    return true;
  }
  return false;
}

Group * find_group(const string & groupname) {
  if (groupname.empty()) return nullptr;
  auto it = s_staticdata.mapHandle.find(groupname);
  if (it == s_staticdata.mapHandle.end()) return nullptr;
  return &(it->second);
}

/************************************************************
 *   services (rcl, polled in spin-once)
 ************************************************************/

static int64_t s_request_handle = 0;
static int64_t s_current_request_handle = 0;

bool send_service_response(context *ctx, EusService & srv, rmw_request_id_t & header, pointer r) {
  if (!has_method(ctx, r, K_ROSEUS_SERIALIZE)) {
    ROSEUS_ERROR("you may not return valid value in service callback of %s", srv.name.c_str());
    return false;
  }
  rclcpp::SerializedMessage serialized_response;
  eus_to_serialized(ctx, r, serialized_response);
  try {
    rclcpp::SerializationBase(srv.ts->response_ts).deserialize_message(&serialized_response, srv.response.data);
  } catch (std::exception & e) {
    ROSEUS_ERROR("failed to deserialize the response of %s: %s", srv.name.c_str(), e.what());
    return false;
  }
  rcl_ret_t ret = rcl_send_response(&srv.service, &header, srv.response.data);
  if (ret != RCL_RET_OK) {
    ROSEUS_ERROR("failed to send response of %s: %s", srv.name.c_str(), rcl_get_error_string().str);
    rcl_reset_error();
    return false;
  }
  return true;
}

void process_service(context *ctx, std::shared_ptr<EusService> srv) {
  while (true) {
    rmw_request_id_t header;
    rcl_ret_t ret = rcl_take_request(&srv->service, &header, srv->request.data);
    if (ret == RCL_RET_SERVICE_TAKE_FAILED) break;
    if (ret != RCL_RET_OK) {
      ROSEUS_ERROR("failed to take request of %s: %s", srv->name.c_str(), rcl_get_error_string().str);
      rcl_reset_error();
      break;
    }
    rclcpp::SerializedMessage serialized_request;
    rclcpp::SerializationBase(srv->ts->request_ts).serialize_message(srv->request.data, &serialized_request);
    pointer req = serialized_to_eus(ctx, srv->cb.msg_class, serialized_request);
    vpush(req);
    int64_t handle = ++s_request_handle;
    int64_t previous_handle = s_current_request_handle;
    s_current_request_handle = handle;
    pointer r = call_eus_function(ctx, srv->cb.fn, srv->cb.args, req);
    s_current_request_handle = previous_handle;
    vpush(r);
    if (r == K_ROSEUS_DEFERRED) {
      // the response is sent later by (ros::send-service-response handle res)
      s_staticdata.mapDeferred[handle] = std::make_pair(srv, header);
    } else {
      send_service_response(ctx, *srv, header, r);
    }
    vpop(); vpop();
  }
}

void process_services(context *ctx, const string & groupname) {
  // copy, callbacks may (un)advertise services
  std::vector<std::shared_ptr<EusService>> services;
  for (auto & it : s_staticdata.mapServiced) {
    if (it.second->groupname == groupname) services.push_back(it.second);
  }
  for (auto & srv : services) process_service(ctx, srv);
}

void unprotect_async_callback(context *ctx, pointer item) {
  pointer l = speval(QASYNC_CALLBACKS), prev = NIL;
  while (iscons(l)) {
    if (ccar(l) == item) {
      if (prev == NIL) setval(ctx, QASYNC_CALLBACKS, ccdr(l));
      else pointer_update(ccdr(prev), ccdr(l));
      return;
    }
    prev = l;
    l = ccdr(l);
  }
}

void process_async_clients(context *ctx) {
  std::vector<std::shared_ptr<EusClient>> clients;
  for (auto & it : s_staticdata.mapAsyncClients) {
    if (!it.second->pending.empty()) clients.push_back(it.second);
  }
  for (auto & client : clients) {
    while (!client->pending.empty()) {
      rmw_service_info_t info;
      rcl_ret_t ret = rcl_take_response_with_info(&client->client, &info, client->response.data);
      if (ret == RCL_RET_CLIENT_TAKE_FAILED) break;
      if (ret != RCL_RET_OK) {
        ROSEUS_ERROR("failed to take response of %s: %s", client->name.c_str(), rcl_get_error_string().str);
        rcl_reset_error();
        break;
      }
      auto it = client->pending.find(info.request_id.sequence_number);
      if (it == client->pending.end()) continue;
      EusCallback cb = it->second;
      client->pending.erase(it);
      rclcpp::SerializedMessage serialized_response;
      rclcpp::SerializationBase(client->ts->response_ts).serialize_message(client->response.data, &serialized_response);
      pointer res = serialized_to_eus(ctx, cb.res_class, serialized_response);
      vpush(res);
      call_eus_function(ctx, cb.fn, cb.args, res);
      unprotect_async_callback(ctx, cb.msg_class);  // msg_class holds the protected item
      vpop();
    }
  }
}

