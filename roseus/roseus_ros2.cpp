// roseus.so for ROS 2
//
// This provides the same ros:: functions as roseus.cpp (ROS 1), on top of
// rclcpp. EusLisp messages are generated by scripts/gen_eus_ros2.py: they
// (de)serialize the CDR payload themselves, so topics use
// rclcpp::GenericPublisher / GenericSubscription with serialized
// messages. Services use rcl directly: the request / response are
// converted between the serialized form and the C++ message struct, which
// is allocated with the introspection type support. This works on every
// ROS 2 distribution, rclcpp::GenericService is only available since
// Kilted.
//
// All the callbacks are called from the EusLisp thread calling
// (ros::spin-once) / (ros::spin), as in ROS 1.

