/************************************************************
 *   Parameters
 *
 *   ROS 2 does not have the parameter server, the parameters are the
 *   ones of this node. "~foo", "foo", "/foo" are the parameter "foo" of
 *   this node, "a/b" is "a.b".
 ************************************************************/

string param_name(const string & key) {
  string k = key;
  if (k.size() > 0 && k[0] == '~') k = k.substr(1);
  if (s_node) {
    string fqn = string(s_node->get_fully_qualified_name()) + "/";
    if (k.compare(0, fqn.size(), fqn) == 0) k = k.substr(fqn.size());
  }
  while (k.size() > 0 && k[0] == '/') k = k.substr(1);
  for (auto & c : k) if (c == '/') c = '.';
  return k;
}

bool eus_list_p(pointer p) { return p == NIL || iscons(p); }

bool alist_p(pointer p) {
  return iscons(p) && iscons(ccar(p)) && !iscons(ccar(ccar(p))) &&
    (issymbol(ccar(ccar(p))) || isstring(ccar(ccar(p)))) && ccar(ccar(p)) != NIL;
}

string alist_key(pointer k) {
  string s = eus_string(issymbol(k) ? k->c.sym.pname : k);
  if (issymbol(k)) for (auto & c : s) c = tolower(c);
  return s;
}

void set_param(context *ctx, const string & name, pointer v) {
  numunion nu;
  if (alist_p(v)) {
    for (pointer a = v; iscons(a); a = ccdr(a)) {
      pointer kv = ccar(a);
      if (!iscons(kv)) continue;
      set_param(ctx, name + "." + alist_key(ccar(kv)), ccdr(kv));
    }
    return;
  }
  rclcpp::ParameterValue value;
  if (isint(v)) {
    value = rclcpp::ParameterValue((int64_t)intval(v));
  } else if (isflt(v)) {
    value = rclcpp::ParameterValue((double)fltval(v));
  } else if (isstring(v)) {
    value = rclcpp::ParameterValue(eus_string(v));
  } else if (v == T) {
    value = rclcpp::ParameterValue(true);
  } else if (v == NIL) {
    value = rclcpp::ParameterValue(false);
  } else if (issymbol(v)) {
    string s = eus_string(v->c.sym.pname);
    for (auto & c : s) c = tolower(c);
    value = rclcpp::ParameterValue(s);
  } else if (iscons(v)) {
    bool all_int = true, all_num = true, all_str = true, all_bool = true;
    for (pointer a = v; iscons(a); a = ccdr(a)) {
      pointer e = ccar(a);
      if (!isint(e)) all_int = false;
      if (!isint(e) && !isflt(e)) all_num = false;
      if (!isstring(e)) all_str = false;
      if (e != T && e != NIL) all_bool = false;
    }
    if (all_int) {
      std::vector<int64_t> vec;
      for (pointer a = v; iscons(a); a = ccdr(a)) vec.push_back(intval(ccar(a)));
      value = rclcpp::ParameterValue(vec);
    } else if (all_num) {
      std::vector<double> vec;
      for (pointer a = v; iscons(a); a = ccdr(a))
        vec.push_back(isint(ccar(a)) ? (double)intval(ccar(a)) : (double)fltval(ccar(a)));
      value = rclcpp::ParameterValue(vec);
    } else if (all_str) {
      std::vector<string> vec;
      for (pointer a = v; iscons(a); a = ccdr(a)) vec.push_back(eus_string(ccar(a)));
      value = rclcpp::ParameterValue(vec);
    } else if (all_bool) {
      std::vector<bool> vec;
      for (pointer a = v; iscons(a); a = ccdr(a)) vec.push_back(ccar(a) == T);
      value = rclcpp::ParameterValue(vec);
    } else {
      ROSEUS_ERROR("ROSEUS_SET_PARAM: unsupported list for %s", name.c_str());
      prinx(ctx, v, ERROUT); flushstream(ERROUT); terpri(ERROUT);
      error(E_MISMATCHARG);
    }
  } else if (isvector(v) && (elmtypeof(v) == ELM_INT || elmtypeof(v) == ELM_FLOAT)) {
    int len = vecsize(v);
    if (elmtypeof(v) == ELM_INT) {
      std::vector<int64_t> vec;
      for (int i = 0; i < len; i++) vec.push_back(v->c.ivec.iv[i]);
      value = rclcpp::ParameterValue(vec);
    } else {
      std::vector<double> vec;
      for (int i = 0; i < len; i++) vec.push_back(v->c.fvec.fv[i]);
      value = rclcpp::ParameterValue(vec);
    }
  } else {
    ROSEUS_ERROR("ROSEUS_SET_PARAM: unknown parameters");
    prinx(ctx, v, ERROUT); flushstream(ERROUT); terpri(ERROUT);
    error(E_MISMATCHARG);
  }
  try {
    if (s_node->has_parameter(name) &&
        s_node->get_parameter(name).get_type() != value.get_type() &&
        s_node->get_parameter(name).get_type() != rclcpp::ParameterType::PARAMETER_NOT_SET) {
      // allow changing the type, as the ROS 1 parameter server
      s_node->undeclare_parameter(name);
    }
    s_node->set_parameter(rclcpp::Parameter(name, value));
  } catch (const std::exception & e) {
    ROSEUS_ERROR("failed to set parameter %s: %s", name.c_str(), e.what());
  }
}

