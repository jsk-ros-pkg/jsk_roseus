// convert the ROS 1 style command line arguments into --ros-args
std::vector<string> ros_arguments(const std::vector<string> & args) {
  std::vector<string> ret;
  bool in_ros_args = false;
  for (const string & arg : args) {
    if (arg == "--ros-args") { in_ros_args = true; ret.push_back(arg); continue; }
    if (in_ros_args) {
      ret.push_back(arg);
      if (arg == "--") in_ros_args = false;
      continue;
    }
    size_t pos = arg.find(":=");
    if (pos == string::npos || pos == 0) continue;
    string key = arg.substr(0, pos), value = arg.substr(pos + 2);
    std::vector<string> converted;
    if (key == "__name") {
      converted = {"-r", "__node:=" + value};
    } else if (key == "__ns") {
      converted = {"-r", "__ns:=" + value};
    } else if (key == "__log" || key == "__master" || key == "__ip" || key == "__hostname") {
      continue;
    } else if (key[0] == '_' && key.size() > 1 && key[1] != '_') {
      // _a/b:=v -> -p a.b:=v (the parameter names of ROS 2 use . as separator)
      string name = key.substr(1);
      for (auto & c : name) if (c == '/') c = '.';
      converted = {"-p", name + ":=" + value};
    } else {
      converted = {"-r", key + ":=" + value};
    }
    ret.push_back("--ros-args");
    ret.insert(ret.end(), converted.begin(), converted.end());
    ret.push_back("--");
  }
  if (in_ros_args) ret.push_back("--");
  return ret;
}

pointer ROSEUS(register context *ctx,int n,pointer *argv)
{
  ckarg(3);
  if( s_bInstalled ) {
    ROSEUS_WARN("ROSEUS is already installed as %s", s_node->get_fully_qualified_name());
    return (T);
  }

  string name = eus_string(argv[0]);
  long options = ckintval(argv[1]);
  std::vector<string> args;
  pointer p = argv[2];
  if (!islist(p) && p != NIL) error(E_NOSEQ);
  while (iscons(p)) {
    if (isstring(ccar(p))) args.push_back(eus_string(ccar(p)));
    p = ccdr(p);
  }

  // convert invalid node name charactors to _, we assume it is '-'
  for (size_t i = 0; i < name.size(); i++)
    if ( ! (isalpha(name[i]) || isdigit(name[i])) ) name[i] = '_';
  if (options & 1) { // anonymous
    std::ostringstream ss;
    ss << name << "_" << getpid() << "_"
       << std::chrono::duration_cast<std::chrono::milliseconds>(
         std::chrono::system_clock::now().time_since_epoch()).count();
    name = ss.str();
  }

  s_staticdata.clear();

  /*
    set locale to none to let C RTL assume logging string can contain non-ascii characters.
  */
  setlocale(LC_ALL, "");

  std::vector<string> ros_args = ros_arguments(args);
  std::vector<const char *> cargv;
  cargv.push_back("roseus");
  for (auto & a : ros_args) cargv.push_back(a.c_str());
  try {
    if (!rclcpp::ok()) {
      rclcpp::init(cargv.size(), cargv.data(), rclcpp::InitOptions(),
                   rclcpp::SignalHandlerOptions::None);
    }
    rclcpp::NodeOptions node_options;
    node_options.allow_undeclared_parameters(true);
    node_options.automatically_declare_parameters_from_overrides(true);
    if (options & 2) node_options.enable_rosout(false);
    s_node = std::make_shared<rclcpp::Node>(name, node_options);
  } catch (const std::exception & e) {
    ROSEUS_ERROR("%s", e.what());
    error(E_MISMATCHARG);
    return(NIL);
  }
  s_staticdata.executor = std::make_shared<rclcpp::executors::SingleThreadedExecutor>();
  s_staticdata.executor->add_node(s_node);
  s_staticdata.rate = std::make_shared<rclcpp::Rate>(50.0, s_node->get_clock());

  s_bInstalled = true;

  // install signal handler for sigint. DO NOT call unix:signal after
  // ros::roseus
  signal(SIGINT, roseusSignalHandler);
  return (T);
}

