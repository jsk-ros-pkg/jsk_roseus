// 4 bytes of the CDR encapsulation header, little endian (CDR_LE)
static const uint8_t CDR_LE_HEADER[4] = {0x00, 0x01, 0x00, 0x00};

struct EusCallback {
  pointer fn;
  pointer args;
  pointer msg_class;  // class of the message, or of the request
  pointer res_class;  // class of the response (services)
};

struct TypedBuffer {
  // a C++ message, allocated with the introspection type support
  const rosidl_typesupport_introspection_cpp::MessageMembers * members = nullptr;
  void * data = nullptr;
  void init(const rosidl_typesupport_introspection_cpp::MessageMembers * m) {
    members = m;
    data = malloc(members->size_of_);
    members->init_function(data, rosidl_runtime_cpp::MessageInitialization::ALL);
  }
  ~TypedBuffer() {
    if (data) {
      members->fini_function(data);
      free(data);
    }
  }
};

struct ServiceTypeSupport {
  std::shared_ptr<rcpputils::SharedLibrary> lib, introspection_lib;
  const rosidl_service_type_support_t * ts = nullptr;
  const rosidl_message_type_support_t * request_ts = nullptr;
  const rosidl_message_type_support_t * response_ts = nullptr;
  const rosidl_typesupport_introspection_cpp::MessageMembers * request_members = nullptr;
  const rosidl_typesupport_introspection_cpp::MessageMembers * response_members = nullptr;

  explicit ServiceTypeSupport(const string & type) {
    lib = rclcpp::get_typesupport_library(type, "rosidl_typesupport_cpp");
    introspection_lib = rclcpp::get_typesupport_library(type, "rosidl_typesupport_introspection_cpp");
    ts = rclcpp::get_service_typesupport_handle(type, "rosidl_typesupport_cpp", *lib);
    const rosidl_service_type_support_t * its = rclcpp::get_service_typesupport_handle(
      type, "rosidl_typesupport_introspection_cpp", *introspection_lib);
    auto members = static_cast<const rosidl_typesupport_introspection_cpp::ServiceMembers *>(its->data);
    request_members = members->request_members_;
    response_members = members->response_members_;
    request_ts = rclcpp::get_message_typesupport_handle(type + "_Request", "rosidl_typesupport_cpp", *lib);
    response_ts = rclcpp::get_message_typesupport_handle(type + "_Response", "rosidl_typesupport_cpp", *lib);
  }
};

struct EusService {
  string name;
  string groupname;
  rcl_service_t service;
  std::shared_ptr<ServiceTypeSupport> ts;
  EusCallback cb;
  TypedBuffer request, response;
  rclcpp::Node::SharedPtr node;
  EusService() : service(rcl_get_zero_initialized_service()) {}
  ~EusService() {
    if (node) {
      rcl_ret_t ret = rcl_service_fini(&service, node->get_node_base_interface()->get_rcl_node_handle());
      (void)ret;
    }
  }
};

