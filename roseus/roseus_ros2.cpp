void set_time(context *ctx, pointer tevent, pointer key, int64_t nanoseconds) {
  csend(ctx, tevent, key, 2, K_ROSEUS_SEC, makeint(nanoseconds / 1000000000));
  csend(ctx, tevent, key, 2, K_ROSEUS_NSEC, makeint(nanoseconds % 1000000000));
}

void timer_callback(std::weak_ptr<TimerData> weak) {
  auto data = weak.lock();
  if (!data) return;
  context *ctx = current_ctx;
  pointer clsptr = NIL;
  for(int i=0; i<nextcix;i++) {
    if(!memcmp(classtab[i].def->c.cls.name->c.sym.pname->c.str.chars,(char *)"TIMER-EVENT",11)) {
      clsptr = classtab[i].def;
    }
  }
  rclcpp::Time now = s_node->now();
  rclcpp::Time current_expected = (data->last_expected.nanoseconds() == 0) ?
    now : data->last_expected + rclcpp::Duration(data->period);
  pointer tevent = NIL;
  if (clsptr != NIL) {
    tevent = makeobject(clsptr);
    vpush(tevent);
    csend(ctx,tevent,K_ROSEUS_INIT,0);
    set_time(ctx, tevent, K_ROSEUS_LAST_EXPECTED, data->last_expected.nanoseconds());
    set_time(ctx, tevent, K_ROSEUS_LAST_REAL, data->last_real.nanoseconds());
    set_time(ctx, tevent, K_ROSEUS_CURRENT_EXPECTED, current_expected.nanoseconds());
    set_time(ctx, tevent, K_ROSEUS_CURRENT_REAL, now.nanoseconds());
    set_time(ctx, tevent, K_ROSEUS_LAST_DURATION, data->last_duration.nanoseconds());
  } else {
    vpush(tevent);
  }
  if (data->oneshot) data->timer->cancel();
  call_eus_function(ctx, data->cb.fn, data->cb.args, tevent);
  vpop();
  data->last_expected = current_expected;
  data->last_real = now;
  data->last_duration = s_node->now() - now;
}

pointer ROSEUS_CREATE_TIMER(register context *ctx,int n,pointer *argv)
{
  isInstalledCheck;
  numunion nu;
  bool oneshot = false;
  string groupname;
  Group *group = nullptr;
  pointer fncallback = NIL, args;
  double period=ckfltval(argv[0]);

  // period callbackfunc args0 ... argsN [:oneshot oneshot] [:groupname groupname]
  bool check_key = true;
  while (check_key) {
    if (n > 1 && issymbol(argv[n-2])) {
      if (argv[n-2] == K_ROSEUS_ONESHOT && issymbol(argv[n-1])) {
        if ( argv[n-1] != NIL ) oneshot = true;
        n -= 2;
      } else if (argv[n-2] == K_ROSEUS_GROUPNAME && isstring(argv[n-1])) {
        groupname = eus_string(argv[n-1]);
        group = find_group(groupname);
        if (!group) {
          ROSEUS_ERROR("Groupname %s is missing. Call (ros::create-nodehandle \"%s\") first.",
                       groupname.c_str(), groupname.c_str());
          return (NIL);
        }
        n -= 2;
      } else {
        check_key = false;
      }
    } else {
      check_key = false;
    }
  }

  fncallback = argv[1];
  // ;; arguments ;;
  args=NIL;
  for (int i=n-1;i>=2;i--) args=cons(ctx,argv[i],args);
  vpush(args);
  protect_from_gc(ctx, fncallback, args);

  auto data = std::make_shared<TimerData>();
  data->cb.fn = callback_function(fncallback);
  data->cb.args = args;
  data->oneshot = oneshot;
  data->period = std::chrono::nanoseconds((int64_t)(period * 1e9));
  data->last_expected = rclcpp::Time(0, 0, s_node->get_clock()->get_clock_type());
  data->last_real = data->last_expected;
  vpop(); // args
  std::weak_ptr<TimerData> weak = data;
  data->timer = rclcpp::create_timer(
    s_node, s_node->get_clock(), rclcpp::Duration(data->period),
    [weak]() { timer_callback(weak); },
    group ? group->callback_group : nullptr);

  std::ostringstream ss;
  ss << reinterpret_cast<long>(fncallback) << " " << reinterpret_cast<long>(data.get());
  ROSEUS_DEBUG("create timer %s at %f (oneshot=%d) (groupname=%s)", ss.str().c_str(), period, oneshot, groupname.c_str());
  s_staticdata.mapTimered[ss.str()] = data;
  return (T);
}

